nums = []

#по значению. Удаляет первое вхождение. Если нет такого - ValueError
#Используется, если надо удалить одно значение из списка, когда не знаем его индекс
nums.remove('ЗНАЧЕНИЕ')

#по значению. Удаляет все вхождения
#когда надо удалить все вхождения
nums = [x for x in nums if x != 20]
nums = list(filter(20, nums))

#по индексу. Возвращает при этом значение
#может использоваться для стеков и очередей. Используется, когда значение нужно удалить и сохранить в переменную
last = nums.pop()
first = nums.pop(0)

#по индексу. Удаляет 1 элемент или срез
#когда нужно удалить элемент по индексу и значение не нужно, или нужно удалить срез
del nums[0]
del nums[0:5]

#удалить ВСЁ
#когда нужно удалить все
nums.clear()